/**
 * Copies the SVG paths of the car makes we trade from `simple-icons` (CC0 data;
 * the marks themselves remain their owners' trademarks — shown nominatively to
 * say which makes we source) into a typed module, so the brands strip can
 * recolour them with CSS (navy at rest, gold on hover) without one request each.
 *
 * Makes simple-icons doesn't carry (e.g. CUPRA, Mercedes-Benz, Alfa Romeo) render as a
 * styled wordmark instead; admins can also upload a logo per brand.
 *
 * Run: bun run build:brands
 */
import { readFileSync, writeFileSync } from "node:fs";

/** [brand slug in the database, simple-icons file] — the same unless noted. */
const SLUGS: Array<[string, string]> = [
  ...[
    "volkswagen",
    "audi",
    "skoda",
    "seat",
    "porsche",
    "bmw",
    "renault",
    "dacia",
    "ford",
    "toyota",
    "volvo",
    "peugeot",
    "bentley",
    "bugatti",
    "citroen",
    "ferrari",
    "fiat",
    "iveco",
    "lamborghini",
    "maserati",
    "mclaren",
    "man",
    "mini",
    "opel",
    "polestar",
    "smart",
    "scania",
    "daf",
  ].map((s): [string, string] => [s, s]),
  ["aston-martin", "astonmartin"],
  ["rolls-royce", "rollsroyce"],
  ["ds", "dsautomobiles"],
];

const entries = SLUGS.map(([slug, icon]) => {
  const svg = readFileSync(`node_modules/simple-icons/icons/${icon}.svg`, "utf8");
  const path = /<path d="([^"]+)"/.exec(svg)?.[1];
  const title = /<title>([^<]+)<\/title>/.exec(svg)?.[1];
  if (!path || !title) throw new Error(`unexpected svg for ${slug}`);
  return `  ${JSON.stringify(slug)}: { title: ${JSON.stringify(title)}, path: ${JSON.stringify(path)} },`;
});

const out = `// GENERATED by scripts/build-brand-logos.ts from simple-icons (CC0). Do not edit by hand.
// The marks are trademarks of their owners, shown to indicate the makes we source.
export const BRAND_LOGOS: Record<string, { title: string; path: string }> = {
${entries.join("\n")}
};
`;
writeFileSync("src/data/brand-logos.ts", out);
process.stdout.write(`wrote ${SLUGS.length} brand paths\n`);
